// Every batch file in packages/core/src/batches/ is registered by a generated index, so adding a batch means adding a file and nothing else.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { root } from '../paths.ts'

const dir = new URL('packages/core/src/batches/', root)

/** The batch numbers that have a file, in order. */
export function batchNumbers(): number[] {
  return readdirSync(dir)
    .flatMap((file) => /^batch-(\d+)\.ts$/.exec(file)?.[1] ?? [])
    .map(Number)
    .sort((a, b) => a - b)
}

/** Rewrite index.ts from the batch files present. Returns true when it changed. */
export function writeBatchIndex(): boolean {
  const numbers = batchNumbers()
  const source = `// GENERATED by tools/src/lib/batches.ts (pnpm seed): one line per batch file. Do not edit.
import type { PoseSpec } from '../poses/dsl.ts'
import type { Recipe } from '../recipe-kit.ts'
${numbers.map((n) => `import * as batch${n} from './batch-${n}.ts'`).join('\n')}

const batches: readonly { recipes: Record<string, Recipe>; poses: Record<string, PoseSpec> }[] = [${numbers.map((n) => `batch${n}`).join(', ')}]

export const recipes: Record<string, Recipe> = Object.assign({}, ...batches.map((b) => b.recipes))
export const poses: Record<string, PoseSpec> = Object.assign({}, ...batches.map((b) => b.poses))
`
  const file = fileURLToPath(new URL('index.ts', dir))
  let before = ''
  try {
    before = readFileSync(file, 'utf8')
  } catch {
    // no index yet
  }
  if (before === source) return false
  writeFileSync(file, source)
  return true
}

/** The path of a batch file, for writing a new one. */
export const batchFile = (n: number): string => fileURLToPath(new URL(`batch-${n}.ts`, dir))
