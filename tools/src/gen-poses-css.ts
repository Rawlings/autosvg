// Generates packages/runtime/src/css/poses.css: the ONE stylesheet that turns pose data in an SVG into motion.
//
//   pnpm css
//
// Its size depends only on the number of channels and beats (CHANNELS and BEATS in packages/core/src/poses/dsl.ts), never on how
// many icons there are. Each icon carries its own numbers as data- attributes; this sheet reads them with typed attr().
//
// Built for cheap style recalculation: a shape only pays for the attributes it actually has. Channel and curve are
// picked with attribute selectors (not arithmetic), amounts are read into variables only where the attribute exists,
// and the working values are registered numbers so nothing is pasted into itself.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { BEATS, CHANNEL_VAR, CHANNELS } from '@icon-canvas/core'
import { cssDir } from './paths.ts'

const out = new URL('poses.css', cssDir)
const channels = Object.entries(CHANNEL_VAR) // [['1', '--icon-motion'], ...]
const is = Array.from({ length: BEATS }, (_, i) => i + 1)
const num = (name: string): string => `attr(data-${name} type(<number>), 0)`

// the sum over beats of (that beat's amount of a property) * (that beat's envelope)
const sum = (letter: string): string => is.map((i) => `var(--${letter}${i}, 0) * var(--e${i})`).join(' + ')

const lines: string[] = []
// which channel drives beat i: a selector per channel, no arithmetic
for (const i of is)
  for (const [k, variable] of channels) lines.push(`[data-c${i}="${k}"] { --p${i}: var(${variable}); }`)
lines.push('[data-b] { --b: attr(data-b type(<number>), 1); }') // where a drawn stroke starts (0: not drawn at rest)
lines.push('[data-o] { --o: attr(data-o type(<number>), 1); }') // opacity at rest (0: hidden at rest)
lines.push('[data-z] { --z: attr(data-z type(<number>), 1); }') // scale at rest (0: scaled to nothing at rest)
// the window and the swings, read only where they are given
for (const i of is) for (const n of 'twn') lines.push(`[data-${n}${i}] { --${n}${i}: ${num(`${n}${i}`)}; }`)
// the amounts, read only where they are given
for (const i of is) for (const l of 'rxyshvqag') lines.push(`[data-${l}${i}] { --${l}${i}: ${num(`${l}${i}`)}; }`)
// each beat's envelope: u is progress through its window; the curve is chosen by attribute (ramp by default)
for (const i of is) {
  lines.push(`[data-c${i}] {
  --u${i}: clamp(0, (abs(var(--p${i}, 0)) - var(--t${i}, 0)) / var(--w${i}, 1), 1);
  --e${i}: calc(sign(var(--p${i}, 0)) * var(--u${i}) * var(--u${i}) * (3 - 2 * var(--u${i})));
}
[data-k${i}="1"] { --e${i}: calc(sign(var(--p${i}, 0)) * sin(pi * var(--u${i}))); }
[data-k${i}="2"] { --e${i}: calc(sign(var(--p${i}, 0)) * sin(2 * pi * var(--n${i}, 2) * var(--u${i})) * (1 - var(--u${i}))); }`)
}

const css = `/*
  Icon poses: motion that lives in the SVG, driven by CSS variables. GENERATED by tools/src/gen-poses-css.ts (pnpm css).

  The SVG carries the data. A part that moves has up to ${BEATS} "beats". Beat i is a set of attributes ending in i:
    data-c  which pose channel drives it (1 to ${CHANNELS})
    data-k  curve: 0 smooth ramp that holds (default), 1 pulse that returns, 2 damped wave that settles
    data-t  data-w   where in the channel's 0 to 1 travel the beat plays: start and length (default 0 and 1)
    data-n  swings of a wave (default 2)
    data-r  rotate (degrees)   data-x data-y  move (icon units)   data-s  scale   data-h data-v  scale x / y only
    data-q  skew x (degrees)   data-a  opacity   data-g  draw: -1 hides the stroke, 0 shows it (needs pathLength="1")
    data-b data-o data-z  where a part starts at rest: drawn amount, opacity, scale (0 for a part that exists only in a state)
  and the part's pivot is data-ox data-oy (default 12 12). The root says what each channel means, e.g. data-pose-1="ring".
  A beat's numbers are the value at the top of its curve; beats add up, so a part can anticipate, move and settle.

  This sheet reads those numbers with typed attr() and multiplies by the consumer's variables, set (as numbers) on the icon
  or any ancestor: a hover rule, a transition, an animation, a scroll timeline or a slider.
    --icon-motion   0 to 1   a momentary gesture: it plays and settles back to rest
    --icon-state    0, 1, 2  the state the icon is in: 0 is its normal look, 1 and up are its named states (the root
                             lists them: data-states="weak off"). A state persists; the beats in between are the transition
    --icon-look-x   -1 to 1  (and --icon-look-y) for icons that look around, such as the eyes
  Strokes that exist only in a state (data-st, data-b="0") are drawn on within their window. Motion and state live side
  by side: an icon can ring while it is off.

  The size of this file depends on the number of channels and beats, never on the number of icons.
  Needs typed attr() (Chrome and Edge 133+). Where it is not supported the icons simply stay still.
  Performance: set the variables on the icon itself or a small wrapper when you can; changing one on an ancestor
  restyles every posed shape below it.
*/

${channels.map(([, variable]) => `@property ${variable} { syntax: '<number>'; inherits: true; initial-value: 0; }`).join('\n')}
${is.flatMap((i) => ['p', 'u', 'e'].map((n) => `@property --${n}${i} { syntax: '<number>'; inherits: false; initial-value: 0; }`)).join('\n')}
@property --L { syntax: '<number>'; inherits: false; initial-value: 1; }
/* every number a beat reads is registered and does not inherit: an unregistered custom property flows down to the shapes inside a
   group, which would give them the group's own rotation or mirror as if it were theirs */
${is.flatMap((i) => [...'rxyshvqag'].map((l) => `@property --${l}${i} { syntax: '<number>'; inherits: false; initial-value: 0; }`)).join('\n')}
${is
  .flatMap((i) =>
    (
      [
        ['t', 0],
        ['w', 1],
        ['n', 2],
      ] as const
    ).map(([l, d]) => `@property --${l}${i} { syntax: '<number>'; inherits: false; initial-value: ${d}; }`),
  )
  .join('\n')}
@property --b { syntax: '<number>'; inherits: false; initial-value: 1; }
@property --o { syntax: '<number>'; inherits: false; initial-value: 1; }
@property --z { syntax: '<number>'; inherits: false; initial-value: 1; }

[data-c1] { transform-origin: 12px 12px; }
[data-ox] { transform-origin: attr(data-ox px, 12px) attr(data-oy px, 12px); }

${lines.join('\n')}

${is.map((i) => `[data-r${i}]`).join(', ')} { rotate: calc((${sum('r')}) * 1deg); }
${[...'xy'].flatMap((l) => is.map((i) => `[data-${l}${i}]`)).join(', ')} {
  translate: calc((${sum('x')}) * 1px) calc((${sum('y')}) * 1px);
}
${[...'shv'].flatMap((l) => is.map((i) => `[data-${l}${i}]`)).join(', ')} {
  scale: calc(var(--z, 1) + ${sum('s')} + ${sum('h')}) calc(var(--z, 1) + ${sum('s')} + ${sum('v')});
}
${is.map((i) => `[data-q${i}]`).join(', ')} { transform: skewX(calc((${sum('q')}) * 1deg)); }
${[...'a'].flatMap((l) => is.map((i) => `[data-${l}${i}]`)).join(', ')}, [data-o] { opacity: clamp(0, var(--o, 1) + ${sum('a')}, 1); }

/* drawing a stroke on and off: the shape carries pathLength="1", so dash lengths are fractions of the stroke */
${is.map((i) => `[data-g${i}]`).join(', ')} {
  --L: clamp(0, var(--b, 1) + ${sum('g')}, 1);
  stroke-dasharray: calc(var(--L) * 1.02) 2; /* a dash of exactly 1 loses the end cap; a hair over keeps it */
  opacity: calc(clamp(0, var(--o, 1) + ${sum('a')}, 1) * min(1, var(--L) * 60));
}
`

writeFileSync(out, css)
console.log(`wrote ${fileURLToPath(out)} (${css.length} bytes, ${CHANNELS} channels, ${BEATS} beats)`)
